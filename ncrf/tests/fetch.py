import os
import pickle
import pooch
import certifi
import operator
import logging

from pathlib import Path
from shutil import rmtree
from typing import Any


logger = logging.getLogger(__name__)

os.environ.setdefault('SSL_CERT_FILE', certifi.where())

RELEASE = '0.3'
TESTING_VERSIONED = f"NCRF-testing-data-{RELEASE}"

# web url to fetch the file
archive_name = f"NCRF-testing-data-{RELEASE}.tar.gz"
url = f"https://codeload.github.com/proloyd/NCRF-testing-data/tar.gz/{RELEASE}"
known_hash = "dab7c0539f2ad031e4752cafe2fceb30440287d66c5821aee593828c71ed853d"
folder_name = "ncrf-testing-data"

# names for lading data
_NAMES = ('meg', 'stim', 'fwd_sol', 'emptyroom')

# volume source space of fwd_sol, regenerated by setup_source_space()
FSAVERAGE_SUBJECT = 'fsaverage'
SOURCE_SPACE = 'vol-7'
SOURCE_SPACING = 7.  # mm
SOURCE_GRID_SHAPE = (23, 29, 25)
# surface source space with geodesic distances, generated by surface_source_space()
SURFACE_SOURCE_SPACE = 'ico-3'
SURFACE_DIST_LIMIT = 0.04  # m; covers a source basis kernel of std up to 7.5 mm


def fetch_dataset(force_download: bool = False) -> Path:
    """Ensure the versioned test dataset is available locally and return its path."""
    # manage local storage
    root_dir = Path(os.path.realpath(os.path.join(__file__, '..', '..', '..')))
    final_path = root_dir / folder_name

    want_version = RELEASE
    ver_fname = final_path / "version.txt"
    outdated = False
    if ver_fname.exists():
        with open(ver_fname) as fid:
            data_version = fid.readline().strip()
        outdated = operator.gt(want_version, data_version)
    else:
        logger.info(
            f"Dataset {folder_name} was not found, downloading"
            f"latest version {want_version}"
        )
        force_download = True

    if outdated:
        logger.info(
            f"Dataset {folder_name} version {data_version} out of date, "
            f"latest version is {want_version}"
        )
        force_download = True

    if not outdated and not force_download:
        return final_path

    # Prepare pooch to fetch the data
    processor = pooch.Untar(extract_dir=root_dir)
    downloader_params = dict(timeout=15, progressbar=True)
    downloader = pooch.HTTPDownloader(**downloader_params)

    urls = {archive_name: url}
    registry = {archive_name: known_hash}
    fetcher = pooch.create(
        path=str(root_dir),
        base_url="",  # Full URLs are given in the `urls` dict.
        version=None,  # Data versioning is decoupled from MNE-Python version.
        urls=urls,
        registry=registry,
        retry_if_failed=2,  # 2 retries = 3 total attempts
    )

    try:
        fetcher.fetch(
            fname=archive_name, downloader=downloader, processor=processor
        )
    except ValueError as err:
        err = str(err)
        if "hash of downloaded file" in str(err):
            raise ValueError(
                f"{err} Consider updating hash of the dataset"
            )
        else:
            raise
    fetcher.fetch(
        fname=archive_name, downloader=downloader, processor=processor
    )
    fname = root_dir / archive_name
    fname.unlink()

    rmtree(final_path, ignore_errors=True)
    os.replace(root_dir / TESTING_VERSIONED, final_path)
    return final_path


def _source_space_path(subjects_dir: Path, src: str) -> Path:
    """Path of fsaverage's ``src`` source space, where eelbrain looks for it."""
    return subjects_dir / FSAVERAGE_SUBJECT / 'bem' / f'{FSAVERAGE_SUBJECT}-{src}-src.fif'


def _fetch_fsaverage(subjects_dir: Path) -> Path:
    """Fetch MNE's fsaverage into ``subjects_dir`` (unless present) and return its directory."""
    import mne

    subjects_dir.mkdir(exist_ok=True)
    return Path(mne.datasets.fetch_fsaverage(subjects_dir=subjects_dir))


def setup_source_space(subjects_dir: Path, vertices: Any) -> None:
    """Generate the ``fwd_sol`` volume source space from MNE's fsaverage, unless it exists.

    The test data only carries the source vertices, not the source space file
    their coordinates are read from. MNE regenerates it quickly, but the result
    depends on MNE's grid placement, so it is checked against the vertices
    before it is written.

    Parameters
    ----------
    subjects_dir
        Directory to fetch fsaverage into and write the source space under.
    vertices
        Vertices of the ``fwd_sol`` source space, which must all lie on the grid.
    """
    import mne
    import numpy as np

    fname = _source_space_path(subjects_dir, SOURCE_SPACE)
    if fname.exists():
        return
    fs_dir = _fetch_fsaverage(subjects_dir)
    bem = fs_dir / 'bem' / 'fsaverage-5120-5120-5120-bem-sol.fif'
    src = mne.setup_volume_source_space(FSAVERAGE_SUBJECT, pos=SOURCE_SPACING, bem=bem, subjects_dir=subjects_dir)
    shape = tuple(int(n) for n in src[0]['shape'])
    if shape != SOURCE_GRID_SHAPE or not np.isin(vertices, src[0]['vertno']).all():
        raise RuntimeError(f"{fname.name}: MNE {mne.__version__} generated a grid of shape {shape} that does not match the test data; source coordinates would be wrong")
    mne.write_source_spaces(fname, src)


def surface_source_space() -> Any:
    """fsaverage ico-3 surface source space with geodesic distances.

    The test data has no surface source space, so it is generated from MNE's
    fsaverage on first use, next to the volume source space of ``fwd_sol``.
    Distances are computed up to :data:`SURFACE_DIST_LIMIT`.

    Returns
    -------
    SourceSpace
        Source dimension over all ico-3 vertices of both hemispheres.
    """
    import mne
    from eelbrain import SourceSpace

    subjects_dir = fetch_dataset() / 'subjects'
    fname = _source_space_path(subjects_dir, SURFACE_SOURCE_SPACE)
    if not fname.exists():
        _fetch_fsaverage(subjects_dir)
        src = mne.setup_source_space(FSAVERAGE_SUBJECT, SURFACE_SOURCE_SPACE.replace('-', ''), add_dist=False, subjects_dir=subjects_dir)
        mne.add_source_space_distances(src, dist_limit=SURFACE_DIST_LIMIT)
        mne.write_source_spaces(fname, src)
    return SourceSpace.from_file(subjects_dir, FSAVERAGE_SUBJECT, SURFACE_SOURCE_SPACE)


def load(name: str, geometry: bool = False) -> Any:
    """Load one of the packaged regression-test fixtures by name.

    Parameters
    ----------
    name
        Fixture name, one of ``'meg'``, ``'stim'``, ``'fwd_sol'``, ``'emptyroom'``.
    geometry
        For ``'fwd_sol'``, make the source coordinates available: on first use,
        fetch fsaverage and generate the source space they are read from.
    """
    folder_name = fetch_dataset()
    if name in _NAMES:
        fname = os.path.join(folder_name, f"{name}.pickled")
    else:
        raise ValueError(f"{name}: not found, check dataset version")
    if geometry and name != 'fwd_sol':
        raise ValueError(f"{name=}: geometry is only available for 'fwd_sol'")
    with open(fname, 'rb') as f:
        v = pickle.load(f)
    if name == 'fwd_sol':
        source = v.get_dim('source')
        # stored relative to the dataset; eelbrain would resolve it against the working directory
        source.subjects_dir = str(folder_name / source.subjects_dir)
        if geometry:
            setup_source_space(Path(source.subjects_dir), source.vertices[0])
    return v
